/**
 * 莫兰迪色系调色板 —— 侧栏 UsageIndicator 与插件面板 CodeBuddyTab 共用。
 *
 * 两条配色规则（互相独立，别混用）：
 *
 * 1. **同一维度的递进用连续色阶。** 到期窗口 1天 → 2天 → 7天 是「时间在推移」这一
 *    个维度上的三个刻度，所以取陶土 → 卡其 → 灰绿的一段渐变：相邻两档总比跨档更
 *    接近，眼睛读出来是一条序列，而不是三个互不相干的色块。
 * 2. **不同维度必须换色相。** 「已用积分」（整体消耗）、「本月到期」（自然月口径）、
 *    到期窗口是三件事，各自占一个色相：灰紫 / 灰蓝 / 暖到绿的色阶。
 *
 * 色值经色差（CIE76）校验：同屏 5 条进度条两两 ΔE 最小 17.1，且到期三档相邻
 * ΔE(17.1) < 跨档 ΔE(32.4) —— 这正是「读起来连续」的量化含义，由 test/palette.test.ts 锁定。
 *
 * 这里**刻意写死十六进制值**，不用 `var(--dsw-alias-state-*)`：主题别名会解析回高饱和
 * 系统色（#e5484d 之类），把莫兰迪整个覆盖掉。莫兰迪是中明度、低饱和的灰调色，深浅
 * 两套主题下都可读，放弃主题联动是有意的取舍。
 */
export const MORANDI = {
  /** ≤1 天内到期。陶土粉（色阶起点）。 */
  urgent: '#baa097',
  /** 1–2 天内到期。卡其（色阶中段）。 */
  warn: '#b9b198',
  /** 2–7 天内到期。灰绿（色阶终点）。 */
  calm: '#93b48e',
  /** 整体消耗／已用积分。灰紫——独立维度，与到期色阶远隔。 */
  used: '#af9ab6',
  /** 本月到期池。灰蓝——又一独立维度。 */
  month: '#8ba1b1',
  /** 本月到期池：低消耗档。淡灰蓝。 */
  monthLow: '#bec9cf',
  /** 本月到期池：高消耗档。深灰蓝。 */
  monthHigh: '#60849f',
  /** 搜索接管生效。灰豆绿。 */
  ok: '#59a67d',
  /** 接管未生效。灰琥珀。 */
  blocked: '#b18c68',
  /** 未接管／未知。暖灰。 */
  neutral: '#9e9e9e',
  /** 控件强调色（开关「开」态）。灰紫红：控件不属于数据色，但同样要离数据色够远。 */
  accent: '#aa6eaa',
} as const

/**
 * 到期窗口的连续色阶，按「≤1天 / 1–2天 / 2–7天」顺序取色。
 * 三档同族递进，读作一条时间轴；不要在这里混入其他维度的颜色。
 */
export const SEGMENT_COLORS = [MORANDI.urgent, MORANDI.warn, MORANDI.calm] as const

/**
 * 月度消耗率 → 预警色。在**同一色相（灰蓝）内升降明度**，而不是换色相：
 * 「本月到期」始终是同一个指标，换色相会让人以为它变成了别的东西。
 *
 * 三档互斥（同一时刻只渲染一档），故它们彼此之间的色差不是约束；
 * 真正的约束是每一档都不能与同屏的到期三档、已用积分撞色，见 palette.test.ts。
 */
export function monthColor(ratio: number): string {
  if (ratio >= 0.85) return MORANDI.monthHigh
  if (ratio >= 0.6) return MORANDI.month
  return MORANDI.monthLow
}

/** 段底色：同一色相降饱和当轨道，实心部分才是已用量——同色相内仍能看出进度。 */
export function tint(color: string): string {
  return `color-mix(in srgb, ${color} 22%, transparent)`
}
