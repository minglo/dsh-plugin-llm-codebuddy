/**
 * 莫兰迪色系调色板 —— 侧栏 UsageIndicator 与插件面板 CodeBuddyTab 共用。
 *
 * 两条配色规则（互相独立，别混用）：
 *
 * 1. **同一维度的递进用连续色阶。** 到期窗口 1天 → 2天 → 7天 是「时间在推移」这一
 *    个维度上的三个刻度，所以取陶土 → 卡其 → 灰绿的一段渐变：相邻两档总比跨档更
 *    接近，眼睛读出来是一条序列，而不是三个互不相干的色块。
 * 2. **不同维度必须换色相。** 「已用积分」（整体消耗）、「本月到期」（自然月口径）、
 *    到期窗口是三件事，各自占一个色相：灰紫 / 灰蓝 / 暖到绿的色阶。
 *
 * 色值经色差（CIE76）校验：同屏 5 条进度条两两 ΔE 最小 17.1，且到期三档相邻
 * ΔE(17.1) < 跨档 ΔE(32.4) —— 这正是「读起来连续」的量化含义，由 test/palette.test.ts 锁定。
 *
 * 这里**刻意写死十六进制值**，不用 `var(--dsw-alias-state-*)`：主题别名会解析回高饱和
 * 系统色（#e5484d 之类），把莫兰迪整个覆盖掉。莫兰迪是中明度、低饱和的灰调色，深浅
 * 两套主题下都可读，放弃主题联动是有意的取舍。
 */
